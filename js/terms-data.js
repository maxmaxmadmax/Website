// Turn one clause's lines into HTML. Bullets are grouped into one list.
// esc = the page's own HTML-escape function.
export function termBodyHtml(lines, esc) {
  let h = '';
  let inList = false;
  lines.forEach((line) => {
    const bullet = line.startsWith('• ');
    if (bullet && !inList) { h += '<ul>'; inList = true; }
    if (!bullet && inList) { h += '</ul>'; inList = false; }
    if (bullet) h += '<li>' + esc(line.slice(2)) + '</li>';
    else if (line.startsWith('## ')) h += '<p class="tc-sub">' + esc(line.slice(3)) + '</p>';
    else h += '<p>' + esc(line) + '</p>';
  });
  if (inList) h += '</ul>';
  return h;
}
